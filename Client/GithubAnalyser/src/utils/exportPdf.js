/* ==========================================================
                DEVELOPER MATURITY
========================================================== */

function getDeveloperLevel() {

  const repos = pdf.data.totalRepos || 0;

  const tech = (pdf.data.knownTech || []).length;

  const topRole =
    getSortedRoles()[0]?.[1] || 0;

  if (
    repos >= 30 &&
    tech >= 20 &&
    topRole >= 80
  )
    return "Advanced";

  if (
    repos >= 15 &&
    tech >= 12 &&
    topRole >= 60
  )
    return "Intermediate";

  return "Beginner";

}

function drawDeveloperAssessment() {

  section("Developer Assessment");

  const level = getDeveloperLevel();

  let description = "";

  switch (level) {

    case "Advanced":

      description =
        "Your GitHub profile demonstrates strong practical engineering experience with broad technology exposure .";

      break;

    case "Intermediate":

      description =
        "You have a solid technical foundation . Continue building larger production-quality projects .";

      break;

    default:

      description =
        "You are building your portfolio . Focus on consistency, practical projects and learning modern technologies .";

  }

  drawMetricGrid([
    {
      title: "Developer Level",
      value: level,
      color: COLORS.primary
    }
  ]);

  moveY(4);

  paragraph(
    description,
    PAGE.margin,
    PAGE.contentWidth
  );

}

