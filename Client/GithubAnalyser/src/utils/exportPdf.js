/* ==========================================================
                BEST ROLE INSIGHT
========================================================== */

function drawBestRoleInsight() {

  section("Primary Career Match");

  const sorted = getSortedRoles();

  if (!sorted.length) {

    paragraph(
      "No role analysis data available.",
      PAGE.margin,
      PAGE.contentWidth
    );

    return;

  }

  const [role, score] = sorted[0];

  const readable =
    categoryDisplayMap[role] || role;

  let verdict = "";

  if (score >= 75)
    verdict =
      "Your GitHub profile strongly aligns with this role and demonstrates an advanced level of practical exposure .";

  else if (score >= 55)
    verdict =
      "Your profile shows good alignment with this role, although additional projects can further strengthen it .";

  else if (score >= 30)
    verdict =
      "You possess foundational skills for this role but require broader project experience .";

  else
    verdict =
      "This role is currently underrepresented within your GitHub portfolio. Data is not sufficient to provide a verdict .";

  paragraph(
    `Best Matched Role: ${readable} (${score.toFixed(
      1
    )}%)\n\n${verdict}`,
    PAGE.margin,
    PAGE.contentWidth
  );

}

