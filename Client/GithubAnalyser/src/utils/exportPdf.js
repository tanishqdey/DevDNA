/* ==========================================================
                METRIC GRID
========================================================== */

function drawMetricGrid(cards = []) {

  const gap = 6;

  const width = (PAGE.contentWidth - gap) / 2;

  const height = 26;

  const startY = pdf.cursorY;

  cards.forEach((card, index) => {

    const row = Math.floor(index / 2);

    const col = index % 2;

    drawStatCard({

      ...card,

      x: PAGE.margin + col * (width + gap),

      y: startY + row * (height + gap),

      width,

      height

    });

  });

  const rows = Math.ceil(cards.length / 2);

  pdf.cursorY = startY + rows * (height + gap);

}

