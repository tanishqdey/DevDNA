const pdf = {
  doc: null,

  cursorY: PAGE.margin,

  currentPage: 1,

  username: "",

  reportDate: "",

  data: null,
};

/* ==========================================================
                    INITIALIZATION
   ========================================================== */

function initPDF(data, username) {
  pdf.doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  pdf.cursorY = PAGE.margin;

  pdf.currentPage = 1;

  pdf.username = username;

  pdf.reportDate = new Date().toLocaleDateString();

  pdf.data = data;
}

/* ==========================================================
                    TYPOGRAPHY ENGINE
   ========================================================== */

function font(
  size = FONT.body,
  weight = "normal",
  color = COLORS.text
) {
  pdf.doc.setFont("helvetica", weight);

  pdf.doc.setFontSize(size);

  pdf.doc.setTextColor(color);
}

/* ==========================================================
                    PAGE MANAGEMENT
   ========================================================== */

function newPage() {
  pdf.doc.addPage();

  pdf.currentPage++;

  pdf.cursorY = PAGE.margin;

  drawHeader();

  drawFooter();
}

function ensureSpace(requiredHeight = 20) {
  if (
    pdf.cursorY + requiredHeight >
    PAGE.height - PAGE.margin
  ) {
    newPage();
  }
}

function moveY(amount) {
  ensureSpace(amount);

  pdf.cursorY += amount;
}

/* ==========================================================
                    HEADER
   ========================================================== */

function drawHeader() {
  pdf.doc.setFillColor(COLORS.primary);

  pdf.doc.rect(
    0,
    0,
    PAGE.width,
    12,
    "F"
  );

  font(
    FONT.small,
    "bold",
    COLORS.white
  );

  pdf.doc.text(
    "DevDNA • Developer Intelligence Report",
    PAGE.margin,
    8
  );
}

/* ==========================================================
                    FOOTER
   ========================================================== */

function drawFooter() {
  const y = PAGE.height - 8;

  pdf.doc.setDrawColor(COLORS.border);

  pdf.doc.line(
    PAGE.margin,
    y - 3,
    PAGE.width - PAGE.margin,
    y - 3
  );

  font(
    FONT.tiny,
    "normal",
    COLORS.muted
  );

  pdf.doc.text(
    "Generated by DevDNA",
    PAGE.margin,
    y
  );

  pdf.doc.text(
    pdf.reportDate,
    PAGE.width / 2,
    y,
    {
      align: "center",
    }
  );

  pdf.doc.text(
    `Page ${pdf.currentPage}`,
    PAGE.width - PAGE.margin,
    y,
    {
      align: "right",
    }
  );
}

/* ==========================================================
                BASIC DRAWING HELPERS
   ========================================================== */

function line(x1, y1, x2, y2) {
  pdf.doc.line(x1, y1, x2, y2);
}

function roundedBox(
  x,
  y,
  w,
  h,
  fill = COLORS.card
) {
  pdf.doc.setFillColor(fill);

  pdf.doc.setDrawColor(COLORS.border);

  pdf.doc.roundedRect(
    x,
    y,
    w,
    h,
    3,
    3,
    "FD"
  );
}

/* ==========================================================
                    TEXT HELPERS
   ========================================================== */

function centerText(
  text,
  y,
  size = FONT.h2,
  color = COLORS.text
) {
  font(size, "bold", color);

  pdf.doc.text(
    text,
    PAGE.width / 2,
    y,
    {
      align: "center",
    }
  );
}

function leftText(
  text,
  x,
  y,
  size = FONT.body,
  weight = "normal",
  color = COLORS.text,
  maxWidth = null
) {
  font(size, weight, color);

  if (maxWidth) {
    pdf.doc.text(text, x, y, { maxWidth });
  } else {
    pdf.doc.text(text, x, y);
  }
}

function rightText(
  text,
  x,
  y,
  size = FONT.body,
  weight = "normal",
  color = COLORS.text
) {
  font(size, weight, color);

  pdf.doc.text(text, x, y, {
    align: "right",
  });
}

function paragraph(
  text,
  x,
  width,
  lineHeight = 5
) {
  font();

  const lines =
    pdf.doc.splitTextToSize(
      text,
      width
    );

  pdf.doc.text(
    lines,
    x,
    pdf.cursorY
  );

  moveY(lines.length * lineHeight);
}

/* ==========================================================
                    SECTION TITLE
   ========================================================== */

function section(title) {
  ensureSpace(16);

  roundedBox(
    PAGE.margin,
    pdf.cursorY,
    PAGE.contentWidth,
    10,
    COLORS.primaryLight
  );

  leftText(
    title,
    PAGE.margin + 5,
    pdf.cursorY + 6.5,
    FONT.h3,
    "bold",
    COLORS.secondary
  );

  moveY(16);
}

