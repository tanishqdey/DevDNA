/* ==========================================================
                    LEARNING ROADMAP
========================================================== */

function getLearningRecommendations() {

  const recommendations = [];

  const knownTech = new Set(
    pdf.data.knownTech || []
  );

  Object.entries(techCategoryMap).forEach(
    ([tech, category]) => {

      if (knownTech.has(tech)) return;

      const meta = getLearningMeta(tech);

      recommendations.push({

        technology: tech,

        category,

        priority: meta.priority,

        difficulty: meta.difficulty,

        duration: meta.duration,

        description: meta.description

      });

    }
  );

  const priorityOrder = {
    High: 0,
    Medium: 1,
    Low: 2
  };

  recommendations.sort((a, b) => {

    const p =
      priorityOrder[a.priority] -
      priorityOrder[b.priority];

    if (p !== 0) return p;

    return a.technology.localeCompare(
      b.technology
    );

  });

  return recommendations;

}

